// Draws the connector icon and writes public/icon.png, public/favicon.ico and lib/icon.ts.
// Same family as QuickPass's icon. Run from the repo root: swift scripts/make-icon.swift
import AppKit
import SwiftUI

let top = Color(red: 0.36, green: 0.55, blue: 1.0)
let bottom = Color(red: 0.29, green: 0.20, blue: 0.86)

struct Icon: View {
    var body: some View {
        ZStack {
            // Full bleed, since connector lists and browser tabs show it small.
            RoundedRectangle(cornerRadius: 230, style: .continuous)
                .fill(LinearGradient(colors: [top, bottom], startPoint: .top, endPoint: .bottom))
                .overlay(
                    RoundedRectangle(cornerRadius: 230, style: .continuous)
                        .fill(LinearGradient(colors: [.white.opacity(0.28), .clear], startPoint: .top, endPoint: .center))
                )
            // An envelope with a sparkle: mail that an assistant can work with.
            Image(systemName: "envelope.fill")
                .font(.system(size: 470, weight: .regular))
                .foregroundStyle(.white.opacity(0.96))
                .shadow(color: .black.opacity(0.18), radius: 14, y: 8)
                .offset(y: 40)
            Image(systemName: "sparkle")
                .font(.system(size: 210, weight: .bold))
                .foregroundStyle(.white)
                .shadow(color: .black.opacity(0.18), radius: 10, y: 6)
                .offset(x: 285, y: -255)
        }
        .frame(width: 1024, height: 1024)
    }
}

@MainActor func png(_ size: Int) -> Data {
    let renderer = ImageRenderer(content: Icon())
    renderer.scale = CGFloat(size) / 1024
    guard let cg = renderer.cgImage else { fatalError("render failed") }
    return NSBitmapImageRep(cgImage: cg).representation(using: .png, properties: [:])!
}

// An .ico file can hold PNG images directly.
func ico(_ images: [(Int, Data)]) -> Data {
    var d = Data([0, 0, 1, 0, UInt8(images.count), 0])
    var offset = 6 + 16 * images.count
    for (size, png) in images {
        d += [UInt8(size % 256), UInt8(size % 256), 0, 0, 1, 0, 32, 0]
        withUnsafeBytes(of: UInt32(png.count).littleEndian) { d += $0 }
        withUnsafeBytes(of: UInt32(offset).littleEndian) { d += $0 }
        offset += png.count
    }
    for (_, png) in images { d += png }
    return d
}

MainActor.assumeIsolated {
    try! png(512).write(to: URL(fileURLWithPath: "public/icon.png"))
    try! ico([(32, png(32)), (64, png(64))]).write(to: URL(fileURLWithPath: "public/favicon.ico"))
    let uri = "data:image/png;base64," + png(64).base64EncodedString()
    try! "// Generated by scripts/make-icon.swift.\nexport const ICON_DATA_URI =\n  \"\(uri)\";\n"
        .write(toFile: "lib/icon.ts", atomically: true, encoding: .utf8)
}
